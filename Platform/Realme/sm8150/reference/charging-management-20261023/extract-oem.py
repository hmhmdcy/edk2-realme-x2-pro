"""Reuse pinned, already downloaded Android R files; no network/phone access."""
from pathlib import Path
import hashlib
import json
import re

ref = Path(__file__).resolve().parent
cache = Path('/mnt/e/edk2-samurai-out/kernel83')
prefix = 'realme-kernel-opensource--realmeX2pro-X3-AndroidR-kernel-source--'
dts = cache / (prefix + 'arch--arm64--boot--dts--19781--pm8150b.dtsi')
text = re.sub(r'/\*.*?\*/|//[^\n]*', '', dts.read_text(), flags=re.S)
values = {k: int(v) for k, v in re.findall(r'qcom,([\w-]+)\s*=\s*<(\d+)>', text)}
rows = [
    (-values['cold_bat_decidegc'], values['little_cold_bat_decidegc'], 'cold'),
    (values['little_cold_bat_decidegc'], values['cool_bat_decidegc'], 'little_cold'),
    (values['cool_bat_decidegc'], values['little_cool_bat_decidegc'], 'cool'),
    (values['little_cool_bat_decidegc'], values['normal_bat_decidegc'], 'little_cool'),
    (values['normal_bat_decidegc'], values['warm_bat_decidegc'], 'normal'),
    (values['warm_bat_decidegc'], values['hot_bat_decidegc'], 'warm'),
]
profile = []
for lo, hi, name in rows:
    key = f'temp_{name}_fastchg_current_ma'
    current = values.get(key, values.get(key + '_low'))
    if key + '_high' in values:
        assert values[key + '_high'] == current, 'Need OEM voltage-dependent branch'
    profile.append([lo, hi, current * 1000, values[f'temp_{name}_vfloat_mv'] * 1000,
                    values[f'{name}_vfloat_over_sw_limit'] * 1000])
assert values['vbatt_num'] == 2
files = [dts, cache / (prefix + 'drivers--power--oppo--charger_ic--oplus_mp2650.c'),
         cache / (prefix + 'drivers--power--oppo--gauge_ic--oplus_bq27541.c'),
         cache / (prefix + 'drivers--power--oppo--charger_ic--oplus_short_ic.c')]
report = {
    'official_commit': '23172a1571bd91156032cc9fef16284a82b63d2c',
    'official_repository': 'https://github.com/realme-kernel-opensource/realmeX2pro-X3-AndroidR-kernel-source',
    'files': {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in files},
    'profile_columns': ['temp_low_decic', 'temp_high_decic_exclusive', 'current_ua',
                        'cell_target_uv', 'cell_ovp_uv'],
    'profile': profile, 'max_charge_seconds': values['max_chg_time_sec'],
    'input_usb_ua': values['input_current_usb_ma'] * 1000,
    'input_cdp_ua': values['input_current_cdp_ma'] * 1000,
    'input_board_max_ua': values['input_current_charger_ma'] * 1000,
    'input_camera_ua': values['input_current_camera_ma'] * 1000,
    'recharge_cell_uv': values['recharge-mv'] * 1000,
    'term_current_ua': values['iterm_ma'] * 1000,
    'scope': 'Normal charging values only; no PD/QC/VOOC/FFC or OEM-init replay',
}
(ref / 'oem-profile.json').write_text(json.dumps(report, indent=2) + '\n')
header = ['/* SPDX-License-Identifier: GPL-2.0-only */',
          '/* Generated by extract-oem.py from pinned official Android R DTS. */',
          'static const struct sm_band sm_oem_bands[] = {']
header += ['\t{ ' + ', '.join(map(str, r)) + ' },' for r in profile]
header += ['};', '#define SM_OEM_MAX_SECONDS ' + str(values['max_chg_time_sec']),
           '#define SM_OEM_INPUT_MAX_UA ' + str(report['input_board_max_ua']), '']
(ref / 'oem-profile.h').write_text('\n'.join(header))
print(json.dumps(report, indent=2))
